// Command chartroles copies the rules of the operator's example roles into
// the console's chart, from the operator module go.mod requires.
//
// The chart grants accounts these roles; copying them by hand would let the
// chart drift from the roles the operator documents and tests. make generate
// runs this, and make verify refuses a copy it did not write.
package main

import (
	"bytes"
	"errors"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"strings"

	rbacv1 "k8s.io/api/rbac/v1"
	utilyaml "k8s.io/apimachinery/pkg/util/yaml"
	"sigs.k8s.io/yaml"
)

// roles maps the name an account's values use to the operator example that
// holds the role.
var roles = []struct{ name, example string }{
	{name: "plan-reader", example: "examples/approver-plan-reader-role.yaml"},
	{name: "desired-state-author", example: "examples/desired-state-author-role.yaml"},
	{name: "diagnostic-reader", example: "examples/diagnostic-reader-role.yaml"},
}

const output = "charts/ptah-console/files/operator-roles.yaml"

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "chartroles:", err)
		os.Exit(1)
	}
}

func run() error {
	dir, version, err := operatorModule()
	if err != nil {
		return err
	}
	var out bytes.Buffer
	fmt.Fprintf(&out, "# Generated by hack/chartroles from the Role in each example of\n"+
		"# github.com/stokaro/ptah-operator %s. Do not edit: run make generate.\n", version)
	for _, role := range roles {
		rules, err := exampleRules(filepath.Join(dir, role.example))
		if err != nil {
			return fmt.Errorf("%s: %w", role.example, err)
		}
		entry, err := yaml.Marshal(map[string]any{role.name: map[string]any{"source": role.example, "rules": rules}})
		if err != nil {
			return err
		}
		out.Write(entry)
	}
	return os.WriteFile(output, out.Bytes(), 0o600)
}

// operatorModule is where the operator module go.mod requires is, and its
// version.
func operatorModule() (dir, version string, err error) {
	listed, err := exec.Command("go", "list", "-m", "-f", "{{.Dir}} {{.Version}}", "github.com/stokaro/ptah-operator").Output()
	if err != nil {
		return "", "", fmt.Errorf("locate the operator module: %w", err)
	}
	dir, version, found := strings.Cut(strings.TrimSpace(string(listed)), " ")
	if !found || dir == "" {
		return "", "", fmt.Errorf("locate the operator module: %q", listed)
	}
	return dir, version, nil
}

// exampleRules is the rules of the one Role in an example file.
func exampleRules(path string) ([]rbacv1.PolicyRule, error) {
	data, err := os.ReadFile(path) // #nosec G304 -- a file of the operator module go.mod requires.
	if err != nil {
		return nil, err
	}
	decoder := utilyaml.NewYAMLOrJSONDecoder(bytes.NewReader(data), 4096)
	var found []rbacv1.PolicyRule
	roles := 0
	for {
		var role rbacv1.Role
		if err := decoder.Decode(&role); errors.Is(err, io.EOF) {
			break
		} else if err != nil {
			return nil, err
		}
		if role.Kind != "Role" {
			continue
		}
		roles++
		found = role.Rules
	}
	if roles != 1 || len(found) == 0 {
		return nil, fmt.Errorf("holds %d Roles; the chart copies exactly one, with rules", roles)
	}
	return found, nil
}
